"""Generate docs/api.md from the public API's signatures and docstrings.

uv run python scripts/gen_api_docs.py          # write docs/api.md
uv run python scripts/gen_api_docs.py --check  # exit 1 if docs/api.md is stale
"""

from __future__ import annotations

import dataclasses
import inspect
import sys
from pathlib import Path

from tracecost import diff, model, prices, report, rollup
from tracecost.readers import dialects, load

OUT = Path(__file__).resolve().parent.parent / "docs" / "api.md"

SECTIONS = [
    (
        "Loading",
        [load, model.Export, model.Generation, model.Span, model.Usage, model.SuppliedCost],
    ),
    (
        "Pricing",
        [
            prices.PriceTable,
            prices.PriceTable.load,
            prices.PriceTable.with_overrides,
            prices.PriceTable.find,
            prices.price_export,
            prices.price_generation,
            prices.price_from_table,
            prices.resolve_rates,
            prices.Cost,
            prices.PricedGeneration,
        ],
    ),
    ("Rollup", [rollup.rollup, rollup.Rollup, rollup.Rollup.by, rollup.Row]),
    ("Diff", [diff.diff, diff.Diff, diff.DiffRow]),
    (
        "Report",
        [
            report.collect_warnings,
            report.Warnings,
            report.header,
            report.cost_table,
            report.cost_json,
            report.diff_table,
            report.diff_json,
        ],
    ),
]

DIALECT_FIELDS = [
    ("model", "model"),
    ("provider", "provider"),
    ("input tokens (total)", "input_tokens"),
    ("output tokens (total)", "output_tokens"),
    ("cache read", "cache_read"),
    ("cache write", "cache_write"),
    ("reasoning", "reasoning"),
    ("session", "session"),
    ("user", "user"),
    ("service tier", "service_tier"),
    ("supplied cost", "cost_total"),
    ("span kind", "kind_key"),
]


def _qualname(obj: object) -> str:
    mod = getattr(obj, "__module__", "")
    name = getattr(obj, "__qualname__", getattr(obj, "__name__", ""))
    return f"{mod}.{name}"


def render() -> str:
    out = [
        "# API reference",
        "",
        "Generated by `scripts/gen_api_docs.py` from the code; do not edit by hand.",
        "`load`, `Export`, `Generation`, `Span`, `Usage` and `SuppliedCost` are also exported",
        "from the top-level `tracecost` package.",
    ]
    for title, objs in SECTIONS:
        out += ["", f"## {title}"]
        for obj in objs:
            name = _qualname(obj)
            if inspect.isclass(obj) and dataclasses.is_dataclass(obj):
                fields = ", ".join(f.name for f in dataclasses.fields(obj))
                out += ["", f"### `{name}`", "", f"Dataclass with fields: `{fields}`."]
            else:
                out += ["", f"### `{name}{inspect.signature(obj, eval_str=True)}`"]
            doc = inspect.getdoc(obj)
            if doc and not doc.startswith(f"{getattr(obj, '__name__', '')}("):
                out += ["", doc]
    out += [
        "",
        "## Attribute dialects",
        "",
        "Which span attributes each reader looks at, in order of preference "
        "(`tracecost.readers.dialects`).",
        "",
        "| field | OTel GenAI (`gen_ai.*`) | OpenInference (`llm.*`) |",
        "|---|---|---|",
    ]
    for label, attr in DIALECT_FIELDS:
        a = ", ".join(f"`{k}`" for k in getattr(dialects.GEN_AI, attr))
        b = ", ".join(f"`{k}`" for k in getattr(dialects.OPENINFERENCE, attr))
        out.append(f"| {label} | {a} | {b} |")
    out += [
        "",
        "Langfuse observations use `usageDetails` (`input`, `output`, `input_cached_tokens`, "
        "`cache_read_input_tokens`, `cache_creation_input_tokens`, `output_reasoning_tokens`), "
        "`costDetails.total`, `model`, `modelParameters.service_tier` and trace-level "
        "`sessionId` / `userId`; see `tracecost.readers.langfuse`.",
    ]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not OUT.is_file() or OUT.read_text() != text:
            sys.exit("docs/api.md is stale: run `uv run python scripts/gen_api_docs.py`")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT}")
